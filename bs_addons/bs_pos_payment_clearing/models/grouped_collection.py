from collections import defaultdict

from odoo import Command, _, api, fields, models
from odoo.exceptions import UserError, ValidationError

_FINALIZE_COLLECTION = object()
_BUILD_COLLECTION = object()


class PosCollectionComponent(models.Model):
    _name = "bs.pos.collection.component"
    _description = "POS Collection Component"
    _check_company_auto = True

    name = fields.Char(required=True, readonly=True)
    session_id = fields.Many2one("pos.session", required=True, readonly=True, check_company=True, ondelete="restrict", index=True)
    company_id = fields.Many2one(related="session_id.company_id", store=True)
    payment_method_id = fields.Many2one("pos.payment.method", required=True, readonly=True, check_company=True, ondelete="restrict")
    journal_id = fields.Many2one("account.journal", required=True, readonly=True, check_company=True, ondelete="restrict")
    partner_id = fields.Many2one("res.partner", readonly=True, check_company=True)
    pos_payment_id = fields.Many2one("pos.payment", readonly=True, check_company=True, ondelete="restrict")
    currency_id = fields.Many2one(related="session_id.currency_id")
    amount = fields.Monetary(readonly=True)
    payment_amount = fields.Monetary(string="Payments", readonly=True)
    difference_amount = fields.Monetary(string="Closing Difference", readonly=True)
    collection_account_id = fields.Many2one("account.account", readonly=True, check_company=True, ondelete="restrict")
    settlement_account_id = fields.Many2one("account.account", readonly=True, check_company=True, ondelete="restrict")
    move_id = fields.Many2one("account.move", required=True, readonly=True, check_company=True, ondelete="restrict")
    line_ids = fields.One2many("account.move.line", "bs_pos_component_id", readonly=True)
    settlement_ids = fields.One2many("account.move", compute="_compute_settlements")
    kind = fields.Selection([("collection", "Collection"), ("difference", "Closing Difference")], required=True, readonly=True)

    @api.depends("line_ids", "move_id.bs_pos_settlement_ids")
    def _compute_settlements(self):
        for component in self:
            component.settlement_ids = component.move_id.bs_pos_settlement_ids.filtered(
                lambda move: move.bs_pos_source_line_id.bs_pos_component_id == component,
            )

    @api.constrains("session_id", "move_id", "journal_id", "payment_method_id", "pos_payment_id")
    def _check_source(self):
        for component in self:
            if (
                not component.move_id.bs_pos_grouped_collection
                or component.move_id.bs_pos_clearing_session_id != component.session_id
                or component.payment_method_id not in component.session_id.payment_method_ids
                or component.journal_id != component.payment_method_id.journal_id
                or component.journal_id.type not in ("cash", "bank")
                or (component.pos_payment_id and (
                    component.pos_payment_id.session_id != component.session_id
                    or component.pos_payment_id.payment_method_id != component.payment_method_id
                ))
            ):
                raise ValidationError(_("Invalid POS collection component source."))

    @api.model_create_multi
    def create(self, vals_list):
        if self.env.context.get("bs_build_collection") is not _BUILD_COLLECTION:
            raise UserError(_("Collection details can only be generated by POS closing."))
        moves = self.env["account.move"].browse([vals["move_id"] for vals in vals_list])
        if moves.filtered(lambda move: move.state != "draft" or move.bs_pos_collection_ready):
            raise ValidationError(_("Collection details can only be created while closing an unfinished session."))
        return super().create(vals_list)

    def write(self, vals):
        raise UserError(_("POS collection details are generated from the session and cannot be edited independently."))

    @api.ondelete(at_uninstall=False)
    def _prevent_deletion(self):
        raise UserError(_("POS collection details cannot be deleted independently."))


class PosSession(models.Model):
    _inherit = "pos.session"

    bs_group_payment_entries = fields.Boolean(readonly=True, copy=False)
    bs_net_cash_difference = fields.Boolean(readonly=True, copy=False)
    bs_collection_move_id = fields.Many2one(
        "account.move", string="Combined Collection Entry", readonly=True, copy=False,
        check_company=True, ondelete="restrict",
    )
    bs_collection_component_ids = fields.One2many("bs.pos.collection.component", "session_id", string="Collection Details", readonly=True)

    @api.model_create_multi
    def create(self, vals_list):
        return super().create([dict(vals, bs_group_payment_entries=True, bs_net_cash_difference=True) for vals in vals_list])

    def write(self, vals):
        for field in {"bs_group_payment_entries", "bs_net_cash_difference", "bs_collection_move_id"} & vals.keys():
            if any((field != "bs_collection_move_id" or session[field]) and self.env["account.move"]._field_will_change(session, vals, field) for session in self):
                raise UserError(_("The collection grouping and source entry cannot be changed on an existing session."))
        return super().write(vals)

    @api.constrains("bs_collection_move_id")
    def _bs_check_collection_move(self):
        for session in self.filtered("bs_collection_move_id"):
            if session.bs_collection_move_id.bs_pos_clearing_session_id != session or not session.bs_collection_move_id.bs_pos_grouped_collection:
                raise ValidationError(_("The collection entry must belong to this POS session."))

    def _bs_get_collection_move(self):
        self.ensure_one()
        self.check_access("write")
        self._bs_check_clearing_configuration()
        self.lock_for_update()
        if not self.bs_collection_move_id:
            self.bs_collection_move_id = self.env["account.move"].with_context(bs_build_collection=_BUILD_COLLECTION).create({
                "move_type": "entry", "journal_id": self.bs_clearing_journal_id.id,
                "company_id": self.company_id.id, "currency_id": self.currency_id.id,
                "date": self._bs_opening_date(), "ref": _("POS collections: %s", self.name),
                "bs_pos_clearing_session_id": self.id, "bs_pos_grouped_collection": True,
            })
        return self.bs_collection_move_id

    def _bs_add_collection_component(self, method, amounts, partner=None, payment=None, difference=0, kind="collection", receivable_values=None):
        self.ensure_one()
        label = _("%(session)s - %(method)s", session=self.name, method=method.display_name)
        common = {"name": label, "partner_id": partner.id if partner else False}
        if not self.currency_id.is_zero(difference):
            difference_account = method.journal_id.loss_account_id if difference < 0 else method.journal_id.profit_account_id
            if not difference_account:
                raise UserError(_("Set a loss/profit account on payment journal %s before closing with a difference.", method.journal_id.display_name))
        collection_account = method.outstanding_account_id
        settlement_account = method.journal_id.default_account_id
        if self.bs_net_cash_difference and method.is_cash_count and method.bs_branch_cash_account_id:
            method._bs_check_branch_cash_account()
            collection_account = method.journal_id.default_account_id
            settlement_account = method.bs_branch_cash_account_id
        if kind == "difference":
            values = self._get_diff_vals(method.id, difference)
            amount = difference
            if values:
                values[0]["account_id"] = collection_account.id
        else:
            receivable = partner.property_account_receivable_id if partner else self._get_receivable_account(method)
            amount = amounts["amount"] + difference
            source = self._debit_amounts(dict(common, account_id=collection_account.id), amounts["amount"], amounts["amount_converted"])
            destination = self._credit_amounts(dict(common, account_id=receivable.id), amounts["amount"], amounts["amount_converted"])
            values = [source, *(receivable_values if receivable_values is not None else [destination])]
            diff_values = self._get_diff_vals(method.id, difference)
            if diff_values:
                extra_source, extra_destination = diff_values
                balance = source.get("debit", 0) - source.get("credit", 0) + extra_source.get("debit", 0) - extra_source.get("credit", 0)
                source.update(debit=max(balance, 0), credit=max(-balance, 0))
                if "amount_currency" in source:
                    source["amount_currency"] += extra_source.get("amount_currency", difference)
                values.append(extra_destination)
        if not values:
            return self.env["account.move.line"]
        if method.journal_id.type == "bank" and self.closing_notes:
            values = [dict(value, name=self.closing_notes) for value in values]
        group = self._bs_get_collection_move()
        if group.state != "draft" or group.bs_pos_collection_ready:
            raise UserError(_("The POS collection entry is already finalized."))
        component = self.env["bs.pos.collection.component"].with_context(bs_build_collection=_BUILD_COLLECTION).create({
            "name": label, "session_id": self.id, "payment_method_id": method.id, "journal_id": method.journal_id.id,
            "partner_id": partner.id if partner else False, "pos_payment_id": payment.id if payment else False,
            "amount": amount, "move_id": group.id, "kind": kind,
            "payment_amount": amounts.get("amount", 0), "difference_amount": difference,
            "collection_account_id": collection_account.id, "settlement_account_id": settlement_account.id,
        })
        values[0]["bs_pos_payment_journal_id"] = method.journal_id.id
        group.with_context(bs_build_collection=_BUILD_COLLECTION).write({
            "line_ids": [Command.create(dict(value, bs_pos_component_id=component.id)) for value in values],
        })
        return component.line_ids.filtered(lambda line: not line.bs_pos_payment_journal_id and line.account_id.account_type == "asset_receivable")

    def _create_combine_account_payment(self, payment_method, amounts, diff_amount):
        if not self.bs_clearing_journal_id or not self.bs_group_payment_entries:
            return super()._create_combine_account_payment(payment_method, amounts, diff_amount)
        return self._bs_add_collection_component(payment_method, amounts, difference=diff_amount)

    def _create_split_account_payment(self, payment, amounts):
        if not self.bs_clearing_journal_id or not self.bs_group_payment_entries:
            return super()._create_split_account_payment(payment, amounts)
        partner = self.env["res.partner"]._find_accounting_partner(payment.partner_id)
        return self._bs_add_collection_component(payment.payment_method_id, amounts, partner=partner, payment=payment)

    def _create_diff_account_move_for_split_payment_method(self, payment_method, diff_amount):
        if not self.bs_clearing_journal_id or not self.bs_group_payment_entries:
            return super()._create_diff_account_move_for_split_payment_method(payment_method, diff_amount)
        self._bs_add_collection_component(payment_method, {}, difference=diff_amount, kind="difference")
        return None

    def _create_cash_statement_lines_and_cash_move_lines(self, data):
        if not self.bs_clearing_journal_id or not self.bs_group_payment_entries:
            return super()._create_cash_statement_lines_and_cash_move_lines(data)
        if self.bs_net_cash_difference:
            return self._bs_create_net_cash_lines(data)
        split_lines = self.env["account.move.line"]
        combine_lines = self.env["account.move.line"]
        split_receivable_values = []
        combine_receivable_values = []
        for payment, amounts in data["split_receivables_cash"].items():
            partner = self.env["res.partner"]._find_accounting_partner(payment.partner_id)
            split_lines |= self._bs_add_collection_component(payment.payment_method_id, amounts, partner=partner, payment=payment)
            split_receivable_values.append(self._get_split_receivable_vals(payment, amounts["amount"], amounts["amount_converted"]))
        for method, amounts in data["combine_receivables_cash"].items():
            if not self.currency_id.is_zero(amounts["amount"]):
                combine_lines |= self._bs_add_collection_component(method, amounts)
                combine_receivable_values.append(self._get_combine_receivable_vals(method, amounts["amount"], amounts["amount_converted"]))
        data.update(
            split_cash_statement_lines=split_lines, combine_cash_statement_lines=combine_lines,
            split_cash_receivable_lines=data["MoveLine"].create(split_receivable_values),
            combine_cash_receivable_lines=data["MoveLine"].create(combine_receivable_values),
        )
        return data

    def _bs_create_net_cash_lines(self, data):
        # Keep each customer's receivable item, but settle one net cash amount per method.
        split_amounts = defaultdict(lambda: {"amount": 0, "amount_converted": 0})
        split_destinations = defaultdict(list)
        split_receivable_values = []
        for payment, amounts in data["split_receivables_cash"].items():
            method = payment.payment_method_id
            partner = self.env["res.partner"]._find_accounting_partner(payment.partner_id)
            for key in ("amount", "amount_converted"):
                split_amounts[method][key] += amounts[key]
            split_destinations[method].append(self._credit_amounts({
                "name": _("%(session)s - %(method)s", session=self.name, method=method.display_name),
                "partner_id": partner.id, "account_id": partner.property_account_receivable_id.id,
            }, amounts["amount"], amounts["amount_converted"]))
            split_receivable_values.append(self._get_split_receivable_vals(payment, amounts["amount"], amounts["amount_converted"]))

        split_lines = self.env["account.move.line"]
        combine_lines = self.env["account.move.line"]
        combine_receivable_values = []
        cash_method = self.payment_method_ids.filtered("is_cash_count")[:1]
        difference = self.cash_register_difference if self.config_id.cash_control else 0
        for method, amounts in split_amounts.items():
            split_lines |= self._bs_add_collection_component(
                method, amounts, difference=difference if method == cash_method else 0,
                receivable_values=split_destinations[method],
            )
        for method, amounts in data["combine_receivables_cash"].items():
            if not self.currency_id.is_zero(amounts["amount"]) or (method == cash_method and not self.currency_id.is_zero(difference)):
                combine_lines |= self._bs_add_collection_component(
                    method, amounts, difference=difference if method == cash_method else 0,
                )
                combine_receivable_values.append(self._get_combine_receivable_vals(method, amounts["amount"], amounts["amount_converted"]))
        # No cash orders (e.g. card-only sales) can still have an opening-float count difference.
        if cash_method and not self.currency_id.is_zero(difference) and not self.bs_collection_component_ids.filtered(
            lambda component: component.payment_method_id == cash_method,
        ):
            self._bs_add_collection_component(cash_method, {}, difference=difference, kind="difference")
        data.update(
            split_cash_statement_lines=split_lines, combine_cash_statement_lines=combine_lines,
            split_cash_receivable_lines=data["MoveLine"].create(split_receivable_values),
            combine_cash_receivable_lines=data["MoveLine"].create(combine_receivable_values),
        )
        return data

    def _post_statement_difference(self, amount):
        if not (self.bs_clearing_journal_id and self.bs_group_payment_entries and self.bs_net_cash_difference):
            return super()._post_statement_difference(amount)
        if self.currency_id.is_zero(amount):
            return None
        method = self.payment_method_ids.filtered("is_cash_count")[:1]
        components = self.bs_collection_component_ids.filtered(lambda component: component.payment_method_id == method)
        if components:
            if not self.currency_id.is_zero(sum(components.mapped("difference_amount")) - amount):
                raise ValidationError(_("The cash count changed while preparing the collection. Please close the session again."))
        else:
            # Native closing skips _create_account_move for an otherwise empty session.
            self._bs_add_collection_component(method, {}, difference=amount, kind="difference")
            self._bs_finalize_collection()
        return None

    def _bs_finalize_collection(self):
        move = self.bs_collection_move_id
        if move and move.state == "draft":
            move.with_context(bs_finalize_collection=_FINALIZE_COLLECTION).bs_pos_collection_ready = True
            move._post(soft=False)

    def _reconcile_account_move_lines(self, data):
        self._bs_finalize_collection()
        return super()._reconcile_account_move_lines(data)

    def _get_related_account_moves(self):
        moves = super()._get_related_account_moves() | self.bs_collection_move_id
        return moves | moves.bs_pos_settlement_ids

    def action_bs_collection_details(self):
        self.ensure_one()
        self.check_access("read")
        return {
            "type": "ir.actions.act_window", "name": _("POS Collection Details"),
            "res_model": "bs.pos.collection.component", "view_mode": "list,form",
            "domain": [("session_id", "=", self.id)], "context": {"create": False},
        }


