from collections import defaultdict

from odoo import api, fields, models, _
from odoo.exceptions import AccessError, UserError

from .adjustment import _INTERNAL, internal


class RecipeFifoLayer(models.Model):
    """Value-only overlays on the remaining part of an incoming FIFO layer.

    Original receipt and historical outgoing values stay unchanged. Future FIFO
    issues consume this value proportionally with the remaining receipt units.
    """
    _name = 'mrp.bom.consumption.fifo.layer'
    _description = 'Recipe FIFO Remaining Value'

    adjustment_move_id = fields.Many2one('stock.move', required=True, ondelete='restrict', index=True)
    receipt_id = fields.Many2one('stock.move', required=True, ondelete='restrict', index=True)
    company_id = fields.Many2one(related='adjustment_move_id.company_id', store=True, index=True)
    date = fields.Datetime(required=True, index=True)
    quantity_basis = fields.Float(required=True)
    value_delta = fields.Float(required=True)

    @api.model_create_multi
    def create(self, vals_list):
        if self.env.context.get('recipe_internal') is not _INTERNAL:
            raise AccessError(_('FIFO value overlays are generated by adjustment confirmation.'))
        return super().create(vals_list)

    def write(self, vals):
        raise AccessError(_('FIFO value overlays are immutable.'))

    def unlink(self):
        raise AccessError(_('FIFO value overlays are immutable.'))


class ProductProduct(models.Model):
    _inherit = 'product.product'

    def _recipe_fifo_rates(self, stack, at_date=None):
        domain = [('receipt_id', 'in', [move.id for move in stack]),
                  ('company_id', '=', self.env.company.id)]
        if at_date:
            domain.append(('date', '<=', at_date))
        rates = defaultdict(float)
        # Valuation must also work for stock/report readers lacking MRP access.
        # Explicit company and receipt restrictions keep this read scoped.
        for layer in self.env['mrp.bom.consumption.fifo.layer'].sudo().search(domain):
            rates[layer.receipt_id.id] += layer.value_delta / layer.quantity_basis
        return rates

    def _run_fifo(self, quantity, lot=None, at_date=None, location=None):
        value = super()._run_fifo(quantity, lot=lot, at_date=at_date, location=location)
        if self.uom_id.compare(quantity, 0) <= 0:
            return value
        stack, first_qty = self._run_fifo_get_stack(lot=lot, at_date=at_date, location=location)
        if not stack:
            return value
        rates = self._recipe_fifo_rates(stack, at_date)
        last_rate = 0
        for move in stack:
            available = first_qty or move._get_valued_qty(lot=lot)
            first_qty = 0
            used = min(quantity, available)
            last_rate = rates[move.id]
            value += used * last_rate
            quantity -= used
            if quantity <= 0:
                break
        if quantity > 0:
            value += quantity * last_rate
        return value

    def _recipe_reconcile_fifo(self, move, target_value):
        self.ensure_one()
        if self.cost_method != 'fifo':
            return
        self.invalidate_recordset(['total_value', 'avg_cost'])
        difference = target_value - self.total_value
        if self.currency_id.is_zero(difference):
            return
        stack, first_qty = self._run_fifo_get_stack()
        remaining = [(receipt, first_qty if i == 0 else receipt._get_valued_qty())
                     for i, receipt in enumerate(stack)]
        total_qty = sum(qty for receipt, qty in remaining)
        if total_qty <= 0 or target_value < 0:
            raise UserError(_('FIFO correction cannot leave a negative value or an empty stock with a residual value. Replenish stock before confirming.'))
        # Allocate in proportion to remaining value, not units: spreading a
        # negative delta uniformly can make a cheap receipt's unit cost negative.
        rates = self._recipe_fifo_rates(stack)
        values = [(receipt, qty, qty * (receipt.value / receipt._get_valued_qty() + rates[receipt.id]))
                  for receipt, qty in remaining if qty > 0]
        total_value = sum(value for receipt, qty, value in values)
        if total_value <= 0 or any(value < 0 for receipt, qty, value in values):
            raise UserError(_('FIFO remaining layers must have a positive total value before this correction.'))
        vals = []
        for receipt, qty, value in values:
            vals.append({'adjustment_move_id': move.id, 'receipt_id': receipt.id,
                         'date': move.date, 'quantity_basis': qty,
                         'value_delta': difference * value / total_value})
        internal(self.env['mrp.bom.consumption.fifo.layer'].sudo()).create(vals)
        self.invalidate_recordset(['total_value', 'avg_cost'])
        self._update_standard_price()
        self.invalidate_recordset(['total_value', 'avg_cost'])
        if self.currency_id.compare_amounts(self.total_value, target_value):
            raise UserError(_('FIFO remaining inventory value did not reconcile with the adjustment entry.'))
