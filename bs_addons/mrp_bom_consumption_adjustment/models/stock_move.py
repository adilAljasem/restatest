from uuid import uuid4

from odoo import api, fields, models, _
from odoo.exceptions import AccessError, UserError
from .adjustment import _INTERNAL


class StockMove(models.Model):
    _inherit = 'stock.move'

    recipe_adjustment_line_id = fields.Many2one(
        'mrp.bom.consumption.line', copy=False, index=True, ondelete='restrict')
    recipe_source_ids = fields.Many2many('mrp.bom.consumption.source', copy=False)
    # Preserve the full computed AVCO/FIFO cost. Product Price precision can
    # round it before multiplication and cause stock/accounting discrepancies.
    recipe_frozen_cost = fields.Float(copy=False)
    # Captured before the original kit move disappears during explosion. Copied
    # to backorders and returns; never inferred from an edited BOM afterwards.
    recipe_root_bom_id = fields.Many2one('mrp.bom', index=True, ondelete='restrict')
    recipe_root_product_id = fields.Many2one('product.product', ondelete='restrict')
    recipe_root_uom_id = fields.Many2one('uom.uom', ondelete='restrict')
    recipe_leaf_uom_id = fields.Many2one('uom.uom', ondelete='restrict')
    recipe_execution_token = fields.Char(index=True)
    recipe_quantity_per_unit = fields.Float(digits=(24, 12))
    recipe_expected_leaves = fields.Json()

    def _recipe_original_bom_line(self):
        self.ensure_one()
        move, seen = self, set()
        while move and move.id not in seen:
            if move.bom_line_id:
                return move.bom_line_id
            seen.add(move.id)
            move = move.origin_returned_move_id
        return self.env['mrp.bom.line']

    @api.model
    def _prepare_merge_moves_distinct_fields(self):
        return super()._prepare_merge_moves_distinct_fields() + [
            'recipe_execution_token', 'recipe_root_bom_id',
            'recipe_quantity_per_unit', 'recipe_adjustment_line_id']

    @api.model_create_multi
    def create(self, vals_list):
        if self.env.context.get('recipe_internal') is not _INTERNAL and any(
                vals.get('recipe_adjustment_line_id') for vals in vals_list):
            raise AccessError(_('Adjustment moves can only be generated by Confirm.'))
        return super().create(vals_list)

    def write(self, vals):
        if self.env.context.get('recipe_internal') is not _INTERNAL:
            if any(m.recipe_adjustment_line_id for m in self) or set(vals) & {
                    'recipe_adjustment_line_id', 'recipe_frozen_cost', 'recipe_source_ids'}:
                raise UserError(_('Adjustment stock moves are managed by their adjustment document.'))
        return super().write(vals)

    @api.depends('recipe_adjustment_line_id.adjustment_id.name')
    def _compute_reference(self):
        super()._compute_reference()
        for move in self.filtered('recipe_adjustment_line_id'):
            move.reference = move.recipe_adjustment_line_id.adjustment_id.name

    def _generate_all_phantom_moves(self, exploded_lines_data):
        vals_list = super()._generate_all_phantom_moves(exploded_lines_data)
        bom = self.env['mrp.bom']._bom_find(
            self.product_id, company_id=self.company_id.id, bom_type='phantom')[self.product_id]
        qty = self.product_uom._compute_quantity(
            self.product_uom_qty or self.quantity, bom.product_uom_id, round=False)
        token = str(uuid4())
        quantities = {}
        for line, data in exploded_lines_data:
            quantities[line.id] = quantities.get(line.id, 0) + data['qty']
        # A repeated leaf through multiple branches is ambiguous in native moves.
        # Keep a zero coefficient so review explicitly requests a verified basis.
        repeated = len(quantities) != len(exploded_lines_data)
        for vals in vals_list:
            vals.update(recipe_root_bom_id=bom.id,
                        recipe_root_product_id=self.product_id.id,
                        recipe_root_uom_id=bom.product_uom_id.id,
                        recipe_leaf_uom_id=vals.get('product_uom'),
                        recipe_execution_token=token,
                        recipe_expected_leaves=list(quantities),
                        recipe_quantity_per_unit=(quantities.get(vals.get('bom_line_id'), 0) / qty
                                                  if qty and not repeated else 0))
        return vals_list

    def _set_value(self, correction_quantity=None):
        adjustments = self.filtered('recipe_adjustment_line_id')
        result = super(StockMove, self - adjustments)._set_value(correction_quantity)
        for move in adjustments:
            move.value = abs(move._get_valued_qty()) * move.recipe_frozen_cost
        if adjustments:
            # Use the normal Odoo 19 cost recomputation with our final move values.
            for company, moves in adjustments.grouped('company_id').items():
                moves.product_id.with_company(company)._update_standard_price()
        return result

    def _get_value(self, forced_std_price=False, at_date=False, ignore_manual_update=False):
        self.ensure_one()
        if self.recipe_adjustment_line_id:
            return abs(self._get_valued_qty()) * self.recipe_frozen_cost
        return super()._get_value(forced_std_price, at_date, ignore_manual_update)

    def _get_value_data(self, forced_std_price=False, at_date=False,
                        ignore_manual_update=False, add_extra_value=True):
        self.ensure_one()
        if self.recipe_adjustment_line_id:
            quantity = abs(self._get_valued_qty())
            return {'value': quantity * self.recipe_frozen_cost, 'quantity': quantity,
                    'description': _('Frozen recipe adjustment cost')}
        return super()._get_value_data(forced_std_price, at_date, ignore_manual_update, add_extra_value)

    def _create_account_move(self):
        # The document posts exactly one entry and links every move to it using
        # stock.move.account_move_id, the native Odoo 19 relationship.
        return super(StockMove, self.filtered(lambda m: not m.recipe_adjustment_line_id))._create_account_move()

    def _prepare_analytic_lines(self):
        if self.recipe_adjustment_line_id:
            return []
        return super()._prepare_analytic_lines()
